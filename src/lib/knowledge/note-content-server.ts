import "server-only";

import { buildKnowledgeNotePath, type KnowledgeNoteKind } from "./note-templates";

export function buildKnowledgeNote(kind: KnowledgeNoteKind, titleInput?: string, now = new Date()) {
  const note = buildKnowledgeNotePath(kind, titleInput, now);
  if (kind === "decision") {
    return {
      ...note,
      content: [
        "---",
        "type: decision",
        `umbra_id: decision:${note.yyyyMmDd}:umbra`,
        "domain: knowledge",
        "status: draft",
        `created: ${note.yyyyMmDd}`,
        `updated: ${note.yyyyMmDd}`,
        "tags: [umbra/decision]",
        "---",
        `# ${note.title}`,
        "",
        "## Decision",
        "",
        "Draft decision created by Umbra after explicit approval.",
        "",
        "## Context",
        "",
        "- ",
        "",
        "## Chosen",
        "",
        "- ",
        "",
        "## Consequences",
        "",
        "- ",
        "",
      ].join("\n"),
    };
  }
  if (kind === "runbook") {
    return {
      ...note,
      content: [
        "---",
        "type: runbook",
        `umbra_id: runbook:${note.yyyyMmDd}:umbra`,
        "domain: knowledge",
        "status: draft",
        "risk: prepare",
        `created: ${note.yyyyMmDd}`,
        `updated: ${note.yyyyMmDd}`,
        "tags: [umbra/runbook]",
        "---",
        `# ${note.title}`,
        "",
        "## Purpose",
        "",
        "- ",
        "",
        "## Preconditions",
        "",
        "- ",
        "",
        "## Steps",
        "",
        "1. ",
        "",
        "## Approval required",
        "",
        "- ",
        "",
        "## Success criteria",
        "",
        "- ",
        "",
        "## Failure modes",
        "",
        "- ",
        "",
      ].join("\n"),
    };
  }
  return {
    ...note,
    content: [
      "---",
      "type: session",
      `umbra_id: session:${note.yyyyMmDd}:umbra`,
      "domain: knowledge",
      "status: draft",
      `created: ${note.yyyyMmDd}`,
      `updated: ${note.yyyyMmDd}`,
      "tags: [umbra/session]",
      "---",
      `# ${note.title} — ${note.yyyyMmDd}`,
      "",
      "## Summary",
      "",
      "Draft session note created by Umbra after explicit approval.",
      "",
      "## Decisions",
      "",
      "- ",
      "",
      "## Actions",
      "",
      "- ",
      "",
      "## Follow-ups",
      "",
      "- ",
      "",
    ].join("\n"),
  };
}
